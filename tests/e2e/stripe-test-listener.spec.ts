import { test, expect } from '@playwright/test'

test('test webhook starts and stops from settings, saves keys privately and preserves the offer being edited', async ({ page, request }, testInfo) => {
  test.setTimeout(90000)
  page.setDefaultTimeout(15000)
  expect((await request.post('/api/billing/test-listener', { data: {} })).status()).toBe(401)
  await page.request.post('/api/auth/login', { data: { email: 'admin@e2e.local', password: 'e2e-password-123' } })
  await page.request.delete('/api/billing/test-listener')
  // This test uses tests/fixtures/stripe-cli.cjs on PATH, never a real Stripe account.
  try {
    await page.goto('/settings?tab=payment')
    const panel = page.getByRole('region', { name: 'Webhook de test automatique' })
    await expect(panel.getByRole('button', { name: 'Générer et démarrer', exact: true })).toBeEnabled()
    await page.getByRole('spinbutton', { name: /Prix unique/ }).fill('349')
    await page.getByLabel('Clé secrète Stripe', { exact: true }).fill('sk_test_listener_browser_fixture')
    await panel.getByRole('button', { name: 'Générer et démarrer', exact: true }).click()
    await expect(panel.getByText('Actif', { exact: true })).toBeVisible()
    await expect(page.getByLabel('Secret de signature du webhook', { exact: true })).toHaveAttribute('placeholder', 'Enregistré')
    await expect(page.getByLabel('Secret de signature du webhook', { exact: true })).toHaveValue('')
    await expect(page.getByLabel('Clé secrète Stripe', { exact: true })).toHaveValue('')
    await expect(page.getByRole('spinbutton', { name: /Prix unique/ })).toHaveValue('349')
    const status = await (await page.request.get('/api/billing/test-listener')).json()
    expect(status).toMatchObject({ state: 'running', secretSaved: true })
    expect(JSON.stringify(status)).not.toMatch(/whsec_|sk_test_/)
    expect((await (await page.request.get('/api/billing')).json()).webhookConfigured).toBe(true)
    await page.setViewportSize({ width: 360, height: 844 })
    expect(await page.evaluate(() => document.documentElement.scrollWidth)).toBeLessThanOrEqual(361)
    await page.screenshot({ path: testInfo.outputPath('stripe-listener-mobile.png'), fullPage: true })
    await page.reload()
    await expect(panel.getByText('Actif', { exact: true })).toBeVisible()
    await panel.getByRole('button', { name: 'Arrêter', exact: true }).click()
    await expect(panel.getByText('Arrêté', { exact: true })).toBeVisible()
    expect((await (await page.request.get('/api/billing/test-listener')).json()).state).toBe('stopped')
    await expect(panel.getByRole('button', { name: 'Arrêter', exact: true })).toBeDisabled()
    await page.getByLabel('Clé secrète Stripe', { exact: true }).fill('sk_live_browser_fixture_rejected')
    await panel.getByRole('button', { name: 'Générer et démarrer', exact: true }).click()
    await expect(panel.getByText(/Les clés réelles ne sont pas acceptées/)).toBeVisible()
    expect((await (await page.request.get('/api/billing/test-listener')).json()).state).toBe('stopped')
    const foreign = await page.request.post('/api/billing/test-listener', { headers: { origin: 'https://foreign.example.test' }, data: {} })
    expect(foreign.status()).toBe(403)
    await page.getByLabel('Clé secrète Stripe', { exact: true }).fill('sk_test_listener_browser_fixture')
    await panel.getByRole('button', { name: 'Générer et démarrer', exact: true }).click()
    await expect(panel.getByText('Actif', { exact: true })).toBeVisible()
    await expect(panel.getByText(/Les clés réelles ne sont pas acceptées/)).toHaveCount(0)
    await panel.getByRole('button', { name: 'Arrêter', exact: true }).click()
    await expect(panel.getByText('Arrêté', { exact: true })).toBeVisible()
  } finally { await page.request.delete('/api/billing/test-listener') }
})
