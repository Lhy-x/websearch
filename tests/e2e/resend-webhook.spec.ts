import { test, expect } from '@playwright/test'

test('Resend webhook can be created, reused, disabled and enabled with a private secret from both settings panels',async({page,request,baseURL},testInfo)=>{
  test.setTimeout(90000)
  page.setDefaultTimeout(15000)
  expect((await request.post('/api/connections/resend-webhook',{data:{base:'https://resend-e2e.example.test'}})).status()).toBe(401)
  await page.request.post('/api/auth/login',{data:{email:'admin@e2e.local',password:'e2e-password-123'}})
  await page.request.put('/api/settings',{data:{runtime:{APP_BASE_URL:'https://configured-origin.example.test'}}})
  try {
    await page.goto('/settings?tab=outreach')
    const panel=page.locator('#resend-webhook')
    await expect(panel.getByRole('heading',{name:'Webhook Resend en un clic'})).toBeVisible()
    await panel.getByLabel('Clé API Resend pour le webhook',{exact:true}).fill('re_e2e_full_access_only')
    await panel.getByLabel('Adresse publique pour Resend',{exact:true}).fill('http://localhost:3100')
    await panel.getByRole('button',{name:'Créer le webhook Resend',exact:true}).click()
    await expect(panel.getByText(/Resend a besoin d’une adresse HTTPS publique/)).toBeVisible()
    await panel.getByLabel('Adresse publique pour Resend',{exact:true}).fill('https://resend-e2e.example.test')
    await panel.getByRole('button',{name:'Créer le webhook Resend',exact:true}).click()
    await expect(panel.getByText('Secret enregistré automatiquement et masqué',{exact:true})).toBeVisible()
    await expect(panel.getByLabel('Clé API Resend pour le webhook',{exact:true})).toHaveValue('')
    await expect(panel.getByText('Activé',{exact:true})).toBeVisible()
    const status=await(await page.request.get('/api/connections/resend-webhook')).json()
    expect(status.secretConfigured&&status.keyConfigured).toBe(true)
    expect(JSON.stringify(status)).not.toMatch(/whsec_|re_e2e_full_access_only/)
    await panel.getByRole('button',{name:'Créer le webhook Resend',exact:true}).click()
    await expect(panel.getByRole('button',{name:'Créer le webhook Resend',exact:true})).toBeEnabled()
    expect((await(await page.request.get('/api/connections/resend-webhook')).json()).webhook.id).toBe(status.webhook.id)
    await panel.getByRole('button',{name:'Désactiver le webhook',exact:true}).click()
    await expect(panel.getByText('Désactivé',{exact:true})).toBeVisible()
    await panel.getByRole('button',{name:'Activer le webhook',exact:true}).click()
    await expect(panel.getByText('Activé',{exact:true})).toBeVisible()
    await page.goto('/settings?tab=connections')
    await page.getByRole('button',{name:'Email',exact:true}).click()
    await expect(panel.getByText('Secret enregistré automatiquement et masqué',{exact:true})).toBeVisible()
    await page.setViewportSize({width:360,height:844})
    expect(await page.evaluate(()=>document.documentElement.scrollWidth)).toBeLessThanOrEqual(361)
    await page.screenshot({path:testInfo.outputPath('resend-webhook-mobile.png'),fullPage:true})
    await panel.getByLabel('Clé API Resend pour le webhook',{exact:true}).fill('re_e2e_restricted_only')
    await panel.getByRole('button',{name:'Créer le webhook Resend',exact:true}).click()
    await expect(panel.getByText(/Resend refuse cette clé/)).toBeVisible()
    expect((await(await page.request.get('/api/connections/resend-webhook')).json()).secretConfigured).toBe(true)
    expect((await page.request.post('/api/connections/resend-webhook',{headers:{origin:'https://foreign.example.test'},data:{base:'https://resend-e2e.example.test'}})).status()).toBe(403)
  } finally {
    await page.request.patch('/api/connections/resend-webhook',{data:{enabled:false}})
    for (const key of ['RESEND_API_KEY','RESEND_WEBHOOK_SECRET']) await page.request.post('/api/settings',{data:{action:'secret',key,value:null}})
    await page.request.put('/api/settings',{data:{runtime:{APP_BASE_URL:baseURL}}})
  }
})
